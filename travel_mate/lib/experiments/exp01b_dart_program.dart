// Travel Mate - Experiment 1(b): A simple Dart program.
// Prints a greeting and adds the cost of a bus ticket and a hotel room.
//
// Run:  dart run lib/experiments/exp01b_dart_program.dart

void main() {
  print("Hello, World! Welcome to Travel Mate.");
  int bus = 450, hotel = 1200;
  int sum = bus + hotel;
  print("The sum of $bus and $hotel is $sum");
  print("Trip cost for bus ticket and hotel = Rs.$sum");
}
